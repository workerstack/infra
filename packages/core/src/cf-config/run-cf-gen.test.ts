import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { afterEach, expect, it } from "vitest";

import { LOCAL_STACK_FILE } from "../local/local-stack-file.constants.ts";
import { logLines } from "../provision/__fixtures__/log-lines.ts";
import { absoluteImports } from "../shared/__fixtures__/absolute-imports.ts";
import { cleanCopies, copyProduct } from "./__fixtures__/copy-product.ts";
import { fakeTypes } from "./__fixtures__/fake-types.ts";
import { jsonObjectSchema } from "./json-object-schema.ts";
import type { JsonObject } from "./json-object.ts";
import { objectAt } from "./object-at.ts";
import { runCfGen } from "./run-cf-gen.ts";

const GEN_TIMEOUT = 30_000;

const SRC = join(import.meta.dirname, "..");

const { runTypes } = fakeTypes();

afterEach(cleanCopies);

function read(file: string): string {
  return readFileSync(file, "utf8");
}

function json(file: string): JsonObject {
  return jsonObjectSchema().parse(JSON.parse(read(file)));
}

async function generated() {
  const { product } = copyProduct();
  const { lines, log } = logLines();

  await runCfGen({ check: false, log, product, runTypes });

  return { api: join(product.root, "api"), lines, log, product };
}

it(
  "writes a Wrangler config and .dev.vars per scope, allocating the rate-limit ids, printing each file",
  async () => {
    const { api, lines, product } = await generated();
    const ids = json(join(product.root, "ratelimit-ids.json"));

    expect(lines).toContain("wrote apps/web/api/.cloudflare/wrangler.local.json");
    expect(lines).toContain("wrote apps/web/api/.dev.vars.prod");
    expect(lines).toContain("wrote apps/web/ratelimit-ids.json");
    expect(Object.keys(objectAt(ids, "web-api") ?? {}).toSorted()).toStrictEqual(["dev", "local", "prod"]);
    expect(json(join(api, ".cloudflare/wrangler.prod.json"))).toMatchObject({
      assets: { directory: join(api, "assets") },
      main: join(api, "src/index.ts"),
      minify: true,
      name: "web-api-prod",
      secrets: { required: ["API_KEY"] },
      upload_source_maps: true,
      vars: { GREETING: "hi prod" },
    });
  },
  GEN_TIMEOUT,
);

it(
  "gives each D1 binding its migrations dir in the owning Worker",
  async () => {
    const { api, product } = await generated();
    const local = json(join(api, ".cloudflare/wrangler.local.json"));

    expect(local["d1_databases"]).toStrictEqual([
      {
        binding: "DB",
        database_id: "db-local-id",
        database_name: "db-local",
        migrations_dir: join(product.root, "db/migrations"),
      },
    ]);
  },
  GEN_TIMEOUT,
);

it(
  "writes .dev.vars.<scope> from the declared secrets' values, and the local URL var in local alone",
  async () => {
    const { api } = await generated();
    const local = read(join(api, ".dev.vars.local"));

    expect(local).toBe(
      '# Generated by infra gen from apps/web/api/cloudflare.config.ts\nAPI_KEY="key-local"\nSITE_URL="http://example.localhost/app"\n',
    );
    expect(read(join(api, ".dev.vars.prod"))).toBe(
      '# Generated by infra gen from apps/web/api/cloudflare.config.ts\nAPI_KEY="key-prod"\n',
    );
    expect(read(join(api, ".cloudflare/.dev.vars"))).toBe(local);
    expect(existsSync(join(api, ".dev.vars.development"))).toBe(false);
  },
  GEN_TIMEOUT,
);

it(
  "writes .dev.vars.development for a Vite app, follows a running stack's origin, and writes nothing twice",
  async () => {
    const { api, log, product } = await generated();
    const stack = join(product.root, LOCAL_STACK_FILE);
    const { lines, log: again } = logLines();

    writeFileSync(join(api, "vite.config.ts"), "export default {};\n");
    mkdirSync(dirname(stack), { recursive: true });
    writeFileSync(
      stack,
      JSON.stringify({
        origin: "http://example.localhost:1356",
        pid: process.pid,
        startedAt: new Date().toISOString(),
      }),
    );
    await runCfGen({ check: false, log, product, runTypes });

    expect(read(join(api, ".dev.vars.development"))).toContain('SITE_URL="http://example.localhost:1356/app"');
    expect(read(join(api, ".dev.vars.local"))).toBe(read(join(api, ".dev.vars.development")));

    await runCfGen({ check: false, log: again, product, runTypes });
    expect(lines).toStrictEqual([]);
  },
  GEN_TIMEOUT,
);

it(
  "fails a declared secret with no value, naming the key and the scope",
  async () => {
    const { product } = copyProduct();
    const kitFile = join(product.root, "infra.config.ts");

    writeFileSync(
      kitFile,
      read(kitFile).replace("API_KEY: `key-${scope}`, ", 'API_KEY: scope === "dev" ? "" : `key-${scope}`, '),
    );

    await expect(runCfGen({ check: false, log: logLines().log, product, runTypes })).rejects.toThrow(
      "API_KEY has no dev value in env",
    );
  },
  GEN_TIMEOUT,
);

const LEAN_INFRA = `import { defineInfraConfig } from "../../../define-infra-config.ts";

export default defineInfraConfig({
  cloudflare: { zone: { domain: "example.com", zoneId: "${"z".repeat(32)}" } },
  env: { dev: { GREETING: "hi dev" }, global: {}, local: { GREETING: "hi local" }, prod: { GREETING: "hi prod" } },
  local: { host: "example.localhost" },
});
`;

const LEAN_WORKER = `import { defineConfig } from "cf/config";

import infra from "../infra.config.ts";

export default defineConfig(({ mode }) => {
  const scope = infra.scope(mode);

  return {
    worker: {
      compatibilityDate: "2026-01-20",
      entrypoint: "./src/index.ts",
      env: {
        ...infra.ratelimits("web-api", scope, { name: "LIMIT_5", simple: { limit: 5, period: 60 } }),
        ...infra.vars(scope, (env) => [env.GREETING]),
      },
      name: infra.name("web-api", scope),
    },
  };
});
`;

it(
  "generates a lean product, no sealedKeys, local.vars or ratelimitIds, its ids in the product root's registry",
  async () => {
    const { product } = copyProduct();

    writeFileSync(join(product.root, "infra.config.ts"), LEAN_INFRA);
    writeFileSync(join(product.root, "api/cloudflare.config.ts"), LEAN_WORKER);
    absoluteImports(product.root, "../../../", SRC);
    await runCfGen({ check: false, log: logLines().log, product, runTypes });

    const ids = json(join(product.root, "ratelimit-ids.json"));

    expect(objectAt(ids, "web-api")).toStrictEqual({
      dev: { LIMIT_5: 2 },
      local: { LIMIT_5: 1 },
      prod: { LIMIT_5: 3 },
    });
    expect(existsSync(join(product.root, "api/.dev.vars.local"))).toBe(false);
    expect(json(join(product.root, "api/.cloudflare/wrangler.prod.json"))).toMatchObject({
      vars: { GREETING: "hi prod" },
    });
  },
  GEN_TIMEOUT,
);
